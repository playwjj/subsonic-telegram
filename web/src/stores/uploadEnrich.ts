// Filling in what an upload is missing: covers (the file's own picture
// first, then an online match) and, when "fill in missing info online" is
// on, tags the file doesn't have. Only ever gaps — a tag the file (or the
// batch's overrides) has is never replaced — and only from a match that
// leaves little doubt: like src/lyrics.ts, nothing beats a confident wrong
// answer. Everything here is best effort; the song itself is uploaded
// either way.
import { parseFileName, searchOnline, setCoverArt, updateTracks, type OnlineMatch, type Song } from "../api/subsonic";
import { prepareCover } from "../utils/image";

// Scores from src/subsonic/online.ts: ≥ 0.95 is artist and title equal
// after normalizing (at most one of them a different version, e.g. "(Live)").
// Albums allow a bit more ("(Deluxe Edition)" on either side is still the
// same cover).
const SONG_CONFIDENT = 0.95;
const ALBUM_CONFIDENT = 0.9;
// Further apart than this, a same-titled match is another recording.
const DURATION_TOLERANCE = 5;

export interface OnlineFill {
  artist?: string;
  title?: string;
  album?: string;
  year?: number;
  genre?: string;
  match?: OnlineMatch; // the song match it all came from
}

// The first match close enough to use without asking (also used by the
// batch "Find online…", BatchIdentifyDialog).
export function confidentMatch(matches: OnlineMatch[], duration?: number): OnlineMatch | null {
  return (
    matches.find(
      (m) =>
        m.score >= SONG_CONFIDENT &&
        // With the file's length known, a match without one can't be checked.
        (duration === undefined || (m.duration !== undefined && Math.abs(m.duration - duration) <= DURATION_TOLERANCE)),
    ) ?? null
  );
}

async function confidentSong(artist: string, title: string, duration?: number): Promise<OnlineMatch | null> {
  return confidentMatch((await searchOnline("song", artist, title)).matches, duration);
}

// "Artist - Title" or "Title - Artist" from a file name, minus a leading
// track number. A plain hyphen needs spaces around it ("Jay-Z", "A-ha").
function splitFileName(stem: string): [string, string] | null {
  const m = /^(.+?)(?:\s+-\s+|\s*[–—]\s*)(.+)$/.exec(stem.replace(/^\d{1,3}\s*[.\-_、]\s*/, ""));
  return m ? [m[1].trim(), m[2].trim()] : null;
}

// Before uploading: an artist (and title) for a file without an artist
// tag, from its name; a clean title for one without a title tag; an album
// for one that would otherwise end up in "Unknown Album". The name is
// split by its " - " first, by Workers AI (parseFileName) when that's not
// enough — every guess confirmed by an online match. null when there's
// nothing to fill or no confident match.
export async function findMissingTags(file: {
  artist?: string;
  title?: string;
  fileName: string;
  folder: string;
  needAlbum: boolean;
  duration?: number;
}): Promise<OnlineFill | null> {
  if (file.artist && file.title && !file.needAlbum) return null;
  const tried = new Set<string>();
  // fill: what the guess adds over the tags.
  const attempt = async (artist: string, title: string, fill: OnlineFill): Promise<OnlineFill | null> => {
    const key = `${artist}\u0000${title}`;
    if (!artist || !title || tried.has(key)) return null;
    tried.add(key);
    const match = await confidentSong(artist, title, file.duration);
    // The file's own spelling, which the match agrees with anyway.
    return match ? { ...fill, ...albumFrom(match, file.needAlbum), match } : null;
  };
  try {
    const stem = file.fileName.replace(/\.[^.]+$/, "");
    if (!file.artist && !file.title) {
      const parts = splitFileName(stem);
      if (parts) {
        for (const [artist, title] of [parts, [parts[1], parts[0]]]) {
          const found = await attempt(artist, title, { artist, title });
          if (found) return found;
        }
      }
    }
    if (file.artist && file.title) return await attempt(file.artist, file.title, {});

    const parsed = await parseFileName(file.fileName, file.folder).catch(() => null);
    const artist = file.artist || parsed?.artist;
    const title = file.title || parsed?.title || (file.artist ? stem : undefined);
    if (!artist || !title) return null;
    return await attempt(artist, title, { artist: file.artist ? undefined : artist, title: file.title ? undefined : title });
  } catch {
    return null;
  }
}

function albumFrom(match: OnlineMatch, needAlbum: boolean): Partial<OnlineFill> {
  return needAlbum && match.album ? { album: match.album, year: match.year, genre: match.genre } : {};
}

function embeddedPicture(file: File): Promise<Blob | null> {
  return (async () => {
    const { parseBlob } = await import("music-metadata");
    const { common } = await parseBlob(file, { skipPostHeaders: true });
    const pictures = common.picture ?? [];
    const picture = pictures.find((p) => p.type === "Cover (front)") ?? pictures[0];
    // "AutoGenerated": placeholder art some tagging tools write (see
    // scripts/import.ts), worse than none.
    if (!picture || picture.description === "AutoGenerated") return null;
    const type = picture.format.startsWith("image/") ? picture.format : "image/jpeg";
    return prepareCover(new Blob([new Uint8Array(picture.data)], { type }));
  })().catch(() => null);
}

// A cover URL that turns out not to exist (Cover Art Archive has none for
// plenty of releases) just moves on to the next match. Whether a cover was
// set: false also when onlyIfMissing found one already there.
async function setFirstCover(id: string, matches: OnlineMatch[], opts: { onlyIfMissing?: boolean }): Promise<boolean> {
  for (const m of matches.slice(0, 3)) {
    if (!m.coverUrl) continue;
    try {
      return await setCoverArt(id, m.coverUrl, opts);
    } catch {
      // try the next one
    }
  }
  return false;
}

// Albums this page has already dealt with, so a 12-track album looks for
// its cover once, not 12 times.
const coveredAlbums = new Set<string>();

// After uploading. A real album (from the tags, the batch's overrides or
// findMissingTags) gets the file's picture as its cover, or else an online
// match's, plus the match's year/genre where the album has none — unless
// it already has a cover (onlyIfMissing, checked by the Worker). A song
// that's only in its folder's album gets a cover of its own instead: that
// album may be a pile of unrelated songs. Returns a note for the upload
// panel about what was added.
export async function addCovers(
  file: File,
  song: Song,
  opts: { realAlbum: boolean; online: boolean; fill?: OnlineFill | null },
): Promise<string | undefined> {
  const notes: string[] = [];
  if (opts.fill?.artist) notes.push("artist from file name");
  else if (opts.fill?.title) notes.push("title from file name");
  if (opts.fill?.album) notes.push("album found online");

  if (opts.realAlbum) {
    if (coveredAlbums.has(song.albumId)) return notes.join(", ") || undefined;
    coveredAlbums.add(song.albumId);
    try {
      const picture = await embeddedPicture(file);
      if (picture) {
        if (await setCoverArt(song.albumId, picture, { onlyIfMissing: true })) notes.push("cover from file");
      } else if (opts.online && song.artist !== "Unknown Artist") {
        const matches = opts.fill?.match?.album === song.album
          ? [opts.fill.match]
          : (await searchOnline("album", song.artist, song.album)).matches.filter((m) => m.score >= ALBUM_CONFIDENT);
        // iTunes first: its covers always exist.
        matches.sort((a, b) => (a.source === b.source ? 0 : a.source === "itunes" ? -1 : 1));
        if (await setFirstCover(song.albumId, matches, { onlyIfMissing: true })) notes.push("cover found online");
        const best = matches[0];
        const year = !song.year && best?.year ? best.year : undefined;
        const genre = !song.genre && best?.genre ? best.genre : undefined;
        if (year || genre) {
          await updateTracks({ songIds: [song.id] }, { year, genre });
          notes.push(`${[year && "year", genre && "genre"].filter(Boolean).join(" & ")} found online`);
        }
      }
    } catch {
      // Telegram's rate limit and the like: let a later song of the album try.
      coveredAlbums.delete(song.albumId);
    }
  } else {
    // The song's own cover, year and genre: its album is just its folder.
    try {
      const picture = await embeddedPicture(file);
      if (picture) {
        await setCoverArt(song.id, picture);
        notes.push("cover from file");
      }
      if (opts.online && song.artist !== "Unknown Artist" && (!picture || !song.year || !song.genre)) {
        const match = opts.fill?.match ?? (await confidentSong(song.artist, song.title, song.duration));
        if (match && !picture && (await setFirstCover(song.id, [match], {}))) notes.push("cover found online");
        const year = !song.year && match?.year ? match.year : undefined;
        const genre = !song.genre && match?.genre ? match.genre : undefined;
        if (year || genre) {
          await updateTracks({ songIds: [song.id] }, { year, genre }, { songLevel: true });
          notes.push(`${[year && "year", genre && "genre"].filter(Boolean).join(" & ")} found online`);
        }
      }
    } catch {
      // no cover, as before
    }
  }
  return notes.join(", ") || undefined;
}
